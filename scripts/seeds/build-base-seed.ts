/**
 * Generates seeds/base.sql (production-safe reference data) from typed content.
 * Run: `npm run seed:build`. The unit test `seeds.test.ts` fails if the committed SQL is stale.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { PERMISSIONS, ROLE_DEFINITIONS } from '../../src/shared/permissions.ts';
import { EXPENSE_CATEGORIES, PAGES, PRODUCTS, SETTINGS } from './content/cms.ts';
import { DIVISIONS } from './content/services.ts';
import { LEGAL_PAGES } from './content/legal.ts';

export const sq = (v: string | number | null | undefined): string =>
  v === null || v === undefined ? 'NULL' : typeof v === 'number' ? String(v) : `'${v.replace(/'/g, "''")}'`;
const ins = (table: string, row: Record<string, string | number | null | undefined>, raw: Record<string, string> = {}) => {
  const cols = [...Object.keys(row), ...Object.keys(raw)];
  const vals = [...Object.values(row).map(sq), ...Object.values(raw)];
  return `INSERT OR IGNORE INTO ${table} (${cols.join(', ')}) VALUES (${vals.join(', ')});`;
};

export function buildBaseSeed(): string {
  const out: string[] = [
    '-- seeds/base.sql: GENERATED by scripts/seeds/build-base-seed.ts. Do not edit by hand.',
    '-- Production-safe reference data. Idempotent (INSERT OR IGNORE): re-running never overwrites owner edits.',
    '',
    '-- Currencies & tax',
    ins('currencies', { code: 'USD', name: 'US Dollar', symbol: '$', minor_digits: 2, active: 1, is_default: 1 }),
    ins('currencies', { code: 'ZWG', name: 'Zimbabwe Gold', symbol: 'ZWG', minor_digits: 2, active: 1, is_default: 0 }),
    ins('tax_rates', { id: 'tax_vat', name: 'VAT 15.5%', rate_bp: 1550, inclusive: 0, active: 0, is_default: 0 }),
    ins('sequences', { key: 'client', next_value: 1 }),
    '',
    '-- Permissions & roles',
  ];
  for (const [key, [module, description]] of Object.entries(PERMISSIONS)) {
    out.push(ins('permissions', { key, module, description }));
  }
  for (const role of ROLE_DEFINITIONS) {
    out.push(ins('roles', { id: `rol_${role.key}`, key: role.key, name: role.name, description: role.description, is_system: 1 }));
    for (const p of role.permissions) out.push(ins('role_permissions', { role_id: `rol_${role.key}`, permission_key: p }));
  }

  out.push('', '-- Settings');
  for (const [key, value] of Object.entries(SETTINGS)) out.push(ins('application_settings', { key, value: JSON.stringify(value) }));

  out.push('', '-- Service divisions & services');
  DIVISIONS.forEach((d, i) => {
    const catId = `scat_${d.slug.replace(/-/g, '_')}`;
    out.push(
      ins('service_categories', {
        id: catId,
        slug: d.slug,
        name: d.name,
        summary: d.summary,
        description: d.description,
        benefits: JSON.stringify(d.benefits),
        deliverables: JSON.stringify(d.deliverables),
        faq: JSON.stringify(d.faq),
        icon: d.icon,
        status: 'active',
        featured: 1,
        sort_order: (i + 1) * 10,
        seo_title: d.seoTitle,
        seo_description: d.seoDescription,
      }),
    );
    d.services.forEach((s, j) =>
      out.push(
        ins('services', {
          id: `svc_${d.slug.replace(/-/g, '_')}__${s.slug.replace(/-/g, '_')}`,
          category_id: catId,
          slug: s.slug,
          name: s.name,
          summary: s.summary,
          pricing_model: 'custom_quote',
          status: 'active',
          sort_order: (j + 1) * 10,
        }),
      ),
    );
  });

  out.push('', '-- Website pages & sections (published defaults)');
  for (const page of [...PAGES, ...LEGAL_PAGES]) {
    const pageId = `pag_${page.key.replace(/-/g, '_')}`;
    out.push(
      ins(
        'website_pages',
        { id: pageId, key: page.key, title: page.title, seo_title: page.seoTitle, seo_description: page.seoDescription, status: 'published' },
        { published_at: "strftime('%Y-%m-%dT%H:%M:%fZ','now')" },
      ),
    );
    page.sections.forEach((s, i) =>
      out.push(
        ins(
          'website_sections',
          {
            id: `sec_${page.key.replace(/-/g, '_')}__${s.key}`,
            page_id: pageId,
            key: s.key,
            type: s.type,
            position: (i + 1) * 10,
            visible: 1,
            draft_content: JSON.stringify(s.content),
            published_content: JSON.stringify(s.content),
          },
          { published_at: "strftime('%Y-%m-%dT%H:%M:%fZ','now')" },
        ),
      ),
    );
  }

  out.push('', '-- Products');
  PRODUCTS.forEach((p, i) =>
    out.push(
      ins('products', {
        id: p.id,
        slug: p.slug,
        name: p.name,
        tagline: p.tagline,
        description: p.description,
        status: p.status,
        interest_form_enabled: p.interestFormEnabled,
        sort_order: (i + 1) * 10,
        published: 1,
      }),
    ),
  );

  out.push('', '-- Expense categories');
  for (const [id, name, description] of EXPENSE_CATEGORIES) out.push(ins('expense_categories', { id, name, description }));

  out.push(
    '',
    '-- Payment accounts & routes. Secrets are Worker secrets named <secret_prefix>_*; never stored here.',
    ins('payment_provider_accounts', {
      id: 'ppa_paynow_usd',
      provider_key: 'paynow',
      label: 'Paynow USD',
      mode: 'test',
      secret_prefix: 'PAYNOW_USD',
      currencies: JSON.stringify(['USD']),
      enabled_methods: JSON.stringify(['ecocash', 'onemoney', 'innbucks', 'card']),
      options: JSON.stringify({ testAuthEmailSecret: 'PAYNOW_TEST_AUTHEMAIL', tokenizationEnabled: false }),
      enabled: 1,
      status_note: 'Test mode until Paynow sets the integration live.',
    }),
    ins('payment_provider_accounts', {
      id: 'ppa_pesepay_main',
      provider_key: 'pesepay',
      label: 'PesePay main',
      mode: 'test',
      secret_prefix: 'PESEPAY_MAIN',
      currencies: JSON.stringify(['USD', 'ZWG']),
      enabled_methods: JSON.stringify([]),
      options: JSON.stringify({}),
      enabled: 1,
      status_note: 'Alternative gateway. Not routed at launch.',
    }),
    ins('payment_routes', {
      id: 'prt_platform_usd_paynow',
      app_key: 'kuzikode-platform',
      currency: 'USD',
      method_code: '*',
      account_id: 'ppa_paynow_usd',
      priority: 100,
      enabled: 1,
    }),
    '',
  );
  return out.join('\n');
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = fileURLToPath(new URL('../../seeds/base.sql', import.meta.url));
  writeFileSync(target, buildBaseSeed());
  console.log(`wrote ${target}`);
}

// ---------------------------------------------------------------- signed URLs

const MAX_SIGNED_TTL_S = 15 * 60;

/** Short-lived signed path for one file: `/api/v1/files/signed/<id>?exp=<unix>&sig=<hmac>`. */
export async function signedFilePath(ctx: RequestContext, fileId: string, ttlSeconds = 300): Promise<string> {
  const exp = Math.floor(ctx.now().getTime() / 1000) + Math.min(ttlSeconds, MAX_SIGNED_TTL_S);
  const sig = await hmacSha256Base64Url(ctx.config.hmacSecret, `file:${fileId}:${exp}`);
  return `/api/v1/files/signed/${encodeURIComponent(fileId)}?exp=${exp}&sig=${sig}`;
}

export async function verifySignedFile(
  ctx: RequestContext,
  fileId: string,
  exp: string | undefined,
  sig: string | undefined,
): Promise<boolean> {
  const e = Number(exp);
  if (!sig || !Number.isInteger(e)) return false;
  const now = Math.floor(ctx.now().getTime() / 1000);
  if (e < now || e > now + MAX_SIGNED_TTL_S) return false;
  return timingSafeEqualString(await hmacSha256Base64Url(ctx.config.hmacSecret, `file:${fileId}:${e}`), sig);
}

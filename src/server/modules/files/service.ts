export interface FileRow {
  id: string;
  r2_key: string;
  original_name: string;
  mime_type: string;
  size_bytes: number;
  sha256: string;
  visibility: 'private' | 'public';
  owner_type: OwnerType;
  owner_id: string | null;
  uploaded_by: string | null;
  created_at: string;
}

export interface StoredFile {
  id: string;
  name: string;
  mime: string;
  size: number;
  type: DetectedType;
  width: number | null;
  height: number | null;
  /** INSERT for the files row: put it in the same batch as the record that references the file. */
  stmt: D1PreparedStatement;
}

/** Staff permission needed to read files of each owner type. */
